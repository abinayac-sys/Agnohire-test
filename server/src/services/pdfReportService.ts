/** Draws a row of KPI cards (label/value/sub), wrapping to further rows as needed. */
function drawUsageKpiCards(
  doc: PDFKit.PDFDocument,
  cards: { label: string; value: string; sub?: string }[],
  startY: number,
): number {
  const margin = 40;
  const contentWidth = doc.page.width - margin * 2;
  const cardGap = 10;
  const cardCols = 4;
  const cardWidth = (contentWidth - cardGap * (cardCols - 1)) / cardCols;
  const cardHeight = 64;
  cards.forEach((c, i) => {
    const col = i % cardCols;
    const row = Math.floor(i / cardCols);
    const x = margin + col * (cardWidth + cardGap);
    const y = startY + row * (cardHeight + cardGap);
    doc.roundedRect(x, y, cardWidth, cardHeight, 10).fillAndStroke(USAGE_COLORS.white, USAGE_COLORS.border);
    doc.fontSize(8).font('Helvetica-Bold').fillColor(USAGE_COLORS.light).text(c.label.toUpperCase(), x + 12, y + 10, { width: cardWidth - 24 });
    doc.fontSize(16).font('Helvetica-Bold').fillColor(USAGE_COLORS.primary).text(c.value, x + 12, y + 26, { width: cardWidth - 24 });
    if (c.sub) doc.fontSize(8).font('Helvetica').fillColor(USAGE_COLORS.light).text(c.sub, x + 12, y + 46, { width: cardWidth - 24 });
  });
  return startY + Math.ceil(cards.length / cardCols) * (cardHeight + cardGap) + 15;
}

/** Draws a simple bordered table with a header row, wrapping to new pages as needed. */
function drawUsageTable(
  doc: PDFKit.PDFDocument,
  title: string,
  columns: { label: string; width: number; align?: 'left' | 'right' }[],
  rows: string[][],
  startY: number,
): number {
  const margin = 40;
  let y = startY;
  if (y > doc.page.height - 140) { doc.addPage(); y = 40; }
  doc.fontSize(14).font('Helvetica-Bold').fillColor(USAGE_COLORS.primary).text(title, margin, y);
  y += 22;

  const drawHeader = () => {
    doc.roundedRect(margin, y, columns.reduce((s, c) => s + c.width, 0), 22, 4).fill(USAGE_COLORS.bg);
    let cx = margin;
    doc.fontSize(9).font('Helvetica-Bold').fillColor(USAGE_COLORS.secondary);
    columns.forEach((c) => {
      doc.text(c.label, cx + 8, y + 6, { width: c.width - 12, align: c.align ?? 'left' });
      cx += c.width;
    });
    y += 26;
  };

  drawHeader();

  if (rows.length === 0) {
    doc.fontSize(9).font('Helvetica').fillColor(USAGE_COLORS.light).text('No data for this range yet.', margin + 8, y);
    return y + 24;
  }

  rows.forEach((row) => {
    doc.fontSize(9).font('Helvetica');
    const rowHeight = Math.max(
      14,
      ...columns.map((c, i) => doc.heightOfString(row[i] ?? '', { width: c.width - 12, lineGap: 1 })),
    ) + 8;

    if (y + rowHeight > doc.page.height - 60) {
      doc.addPage();
      y = 40;
      drawHeader();
    }

    let cx = margin;
    doc.fontSize(9).font('Helvetica').fillColor(USAGE_COLORS.text);
    columns.forEach((c, i) => {
      doc.text(row[i] ?? '', cx + 8, y, { width: c.width - 12, align: c.align ?? 'left', lineGap: 1 });
      cx += c.width;
    });
    doc.moveTo(margin, y + rowHeight).lineTo(margin + columns.reduce((s, c) => s + c.width, 0), y + rowHeight).strokeColor(USAGE_COLORS.border).lineWidth(0.5).stroke();
    y += rowHeight + 4;
  });

  return y + 20;
}

/** AI token usage report — mirrors the Usage Monitor "AI Token Usage" tab. */
