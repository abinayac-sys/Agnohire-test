      const addSection = (title: string, yPos: number, drawLine: boolean = true) => {
        if (yPos > doc.page.height - 100) { doc.addPage(); yPos = 50; }
        doc.fontSize(14).font('Helvetica-Bold').fillColor('#1e293b').text(title, margin, yPos);
        if (drawLine) {
          doc.moveTo(margin, yPos + 18).lineTo(pageWidth - margin, yPos + 18).strokeColor('#cbd5e1').lineWidth(1).stroke();
        }
        return yPos + 30;
      };

      // ─── Job Details ───
      currentY = addSection('Job Details', currentY);
      
      const formatCurrency = (val: any) => val ? `${val}` : '';
      const budgetStr = (job.budgetMin || job.budgetMax) 
        ? `${formatCurrency(job.budgetMin)} - ${formatCurrency(job.budgetMax)}`
        : 'Not specified';
      
