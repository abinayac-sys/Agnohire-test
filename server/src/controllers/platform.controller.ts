/** Full name of the requesting superadmin, for the "Generated by" line on exported reports. */
async function requesterName(req: Request): Promise<string> {
  const user = await prisma.user.findUnique({ where: { id: req.user!.sub }, select: { fullName: true } });
  return user?.fullName ?? 'Superadmin';
}

function parseRangeDays(req: Request): number {
  const raw = Number(req.query.days);
  if (!Number.isFinite(raw) || raw <= 0) return 30;
  return Math.min(Math.round(raw), 365);
}

