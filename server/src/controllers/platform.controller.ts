/**
 * Impersonate (sign into) a tenant the operator created. Mints a full session
 * for the tenant owner and swaps the refresh cookie to it, so the SPA becomes
 * that owner. Restricted to the creating operator.
 */
export const tenantLogin = asyncHandler(async (req: Request, res: Response) => {
  const ownerUserId = await tenantAdmin.assertCreatedByAndGetOwner(req.params.id, req.user!.sub);
  // The owner lives in another tenant, so mint their session under a platform
  // bypass — the operator's own tenant scope would otherwise hide the user.
  // This is the one path allowed to skip the tenant-approval gate, so an
  // operator can enter a tenant they are still reviewing. The flag is
  // persisted on the refresh token, so the exemption survives rotation (the SPA
  // re-bootstraps through /refresh) without exempting anybody else.
  const tokens = await runAsPlatform(() =>
    loginByUserId(ownerUserId, req, { impersonated: true }),
  );
  await recordAudit(req, {
    action: 'WORKSPACE_IMPERSONATE',
    entity: 'Tenant',
    entityId: req.params.id,
    description: `Signed in as workspace owner ${tokens.user.email}`,
  });
  setRefreshCookie(res, tokens.refreshToken, tokens.refreshExpiresAt);
  return ok(res, { accessToken: tokens.accessToken, user: tokens.user });
});

