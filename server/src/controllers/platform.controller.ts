export const exportAiUsagePdf = asyncHandler(async (req: Request, res: Response) => {
  const days = parseRangeDays(req);
  const [summary, byTenant, byFeature, byModel] = await Promise.all([
    aiUsage.getUsageSummary(days),
    aiUsage.getUsageByTenant(days),
    aiUsage.getUsageByFeature(days),
    aiUsage.getUsageByModel(days),
  ]);
  const { generateAiUsagePDF } = await import('../services/pdfReportService.js');
  const { buffer, filename } = await generateAiUsagePDF({ summary, byTenant, byFeature, byModel }, days, await requesterName(req));
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', `attachment; filename="${filename}"`);
  res.send(buffer);
});

